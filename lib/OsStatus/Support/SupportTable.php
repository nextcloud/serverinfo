namespace OCA\ServerInfo\OsStatus\Support;

use OCA\ServerInfo\OsStatus\OsRelease;

/**
 * Looks a release up in the support dates bundled with the app.
 *
 * The table is generated from endoflife.date by build/update-os-support.php
 * before each release; nothing is fetched at runtime.
 *
 * @psalm-api
 */
class SupportTable {
	/** @var array{generatedAt?: string, cycles?: array<string, string>, rolling?: list<string>, releases?: array<string, array<string, string>>}|null */
	private ?array $table = null;

	private string $file = __DIR__ . '/../../../resources/os-support.json';

	/**
	 * A table read from another file than the bundled one.
	 */
	public static function fromFile(string $file): self {
		$table = new self();
		$table->file = $file;

		return $table;
	}

	public function lookup(OsRelease $release): SupportStatus {
		$table = $this->load();
		$dataDate = $table['generatedAt'] ?? null;

		if ($this->isRolling($release, $table['rolling'] ?? [])) {
			return new SupportStatus(true, null, dataDate: $dataDate);
		}

		$id = $this->tableId($release);
		$cycleKind = $table['cycles'][$id] ?? null;
		if ($cycleKind === null || $release->versionId === null) {
			return SupportStatus::unknown($dataDate);
		}

		$parts = explode('.', $release->versionId);
		$cycle = $cycleKind === 'minor' && isset($parts[1]) ? $parts[0] . '.' . $parts[1] : $parts[0];
		$entry = $table['releases'][$id . ':' . $cycle] ?? null;
		if ($entry === null) {
			return SupportStatus::unknown($dataDate);
		}

		return SupportStatus::fromArray([
			'rolling' => false,
			'securityEnds' => $entry['securityEnds'] ?? null,
			'extendedEnds' => $entry['extendedEnds'] ?? null,
			'extended' => $entry['extended'] ?? null,
			'ltsFrom' => $entry['ltsFrom'] ?? null,
			'dataDate' => $dataDate,
		]);
	}

	/**
	 * @param list<string> $rolling
	 */
	private function isRolling(OsRelease $release, array $rolling): bool {
		if (in_array($release->id, $rolling, true)) {
			return true;
		}

		// Arch derivatives follow Arch's rolling model whatever they call themselves.
		return in_array('arch', $release->idLike, true);
	}

	private function tableId(OsRelease $release): string {
		return match (true) {
			$release->id === 'centos' && stripos($release->name, 'stream') !== false => 'centos-stream',
			default => $release->id,
		};
	}

	/**
	 * @return array{generatedAt?: string, cycles?: array<string, string>, rolling?: list<string>, releases?: array<string, array<string, string>>}
	 */
	private function load(): array {
		if ($this->table !== null) {
			return $this->table;
		}

		$json = @file_get_contents($this->file);
		$decoded = is_string($json) ? json_decode($json, true) : null;

		/** @psalm-suppress MixedPropertyTypeCoercion the file is generated by build/update-os-support.php */
		$this->table = is_array($decoded) ? $decoded : [];

		return $this->table;
	}
}
